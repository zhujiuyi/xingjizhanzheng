-- Real astronomical site positions; existing anchor xyz are bounded local encoding.
-- No macro coordinate enters a Godot Vector3, transform, collider or camera position.
CREATE TABLE site_defs (
 site_id TEXT PRIMARY KEY,
 sector_id TEXT NOT NULL REFERENCES sector_defs(sector_id),
 display_name TEXT NOT NULL,
 site_kind TEXT NOT NULL CHECK(site_kind IN ('station','gate','resource','signal','encounter')),
 x_m REAL NOT NULL CHECK(abs(x_m)<1e15), y_m REAL NOT NULL CHECK(abs(y_m)<1e15), z_m REAL NOT NULL CHECK(abs(z_m)<1e15),
 pivot_x_m REAL NOT NULL CHECK(abs(pivot_x_m)<1e6), pivot_y_m REAL NOT NULL CHECK(abs(pivot_y_m)<1e6), pivot_z_m REAL NOT NULL CHECK(abs(pivot_z_m)<1e6),
 local_radius_m REAL NOT NULL CHECK(local_radius_m>0 AND local_radius_m<=1e6),
 UNIQUE(site_id,sector_id)
) STRICT;
CREATE TABLE anchor_site_defs (
 anchor_id TEXT PRIMARY KEY REFERENCES anchor_defs(anchor_id),
 site_id TEXT NOT NULL REFERENCES site_defs(site_id)
) STRICT;
CREATE TABLE celestial_defs (
 celestial_id TEXT PRIMARY KEY,
 sector_id TEXT NOT NULL REFERENCES sector_defs(sector_id),
 display_name TEXT NOT NULL,
 celestial_kind TEXT NOT NULL CHECK(celestial_kind IN ('star','planet')),
 x_m REAL NOT NULL CHECK(abs(x_m)<1e15), y_m REAL NOT NULL CHECK(abs(y_m)<1e15), z_m REAL NOT NULL CHECK(abs(z_m)<1e15),
 radius_m REAL NOT NULL CHECK(radius_m>0 AND radius_m<1e11)
) STRICT;

