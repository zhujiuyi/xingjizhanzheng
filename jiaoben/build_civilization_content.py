"""Author the reviewed civilization SQL extension from the immutable v0.7 seed.

Runtime reads the emitted SQL/catalog only. This authoring tool never opens a
player database or rewrites historical catalog/progress SQL.
"""
from pathlib import Path
import json
import math
import sqlite3

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / 'code/database'
AU = 149_597_870_700.0


def generate():
    c = sqlite3.connect(':memory:')
    c.row_factory = sqlite3.Row
    c.executescript('\n'.join((DB / name).read_text(encoding='utf-8') for name in
                            ('catalog_schema.sql', 'catalog_seed.sql', 'space_v7.sql')))
    c.executescript((DB / 'civilization_schema.sql').read_text(encoding='utf-8'))
    output = ['-- Reviewed civilization expansion; generated by jiaoben/build_civilization_content.py.\n']
    orbit_indices = {}

    def atom(value):
        if value is None:
            return 'NULL'
        if isinstance(value, str):
            return "'" + value.replace("'", "''") + "'"
        if isinstance(value, float):
            assert math.isfinite(value)
        return str(value)

    def emit(sql):
        c.execute(sql)
        output.append(sql + ';\n')

    def insert(table, row):
        emit('INSERT INTO ' + table + ' (' + ','.join(row) + ') VALUES (' + ','.join(map(atom, row.values())) + ')')

    def rows(table, **where):
        clause = ' WHERE ' + ' AND '.join(key + '=?' for key in where) if where else ''
        return [dict(row) for row in c.execute('SELECT * FROM ' + table + clause, tuple(where.values()))]

    def clone(table, key, old, new, **overrides):
        for row in rows(table, **{key: old}):
            row.update({key: new, **overrides})
            insert(table, row)

    def anchor(id_, sector, kind, xyz, site, safe=0, radius=500):
        insert('anchor_defs', dict(anchor_id=id_, sector_id=sector, anchor_kind=kind,
               x_m=xyz[0], y_m=xyz[1], z_m=xyz[2], yaw_rad=0.0,
               interaction_radius_m=float(radius), safe_radius_m=float(safe)))
        insert('anchor_site_defs', dict(anchor_id=id_, site_id=site))

    def orbital_point(sector, orbital):
        index = orbit_indices.get(sector, 0)
        x = orbital[0] * (1 + (index % 9) * .04)
        z = orbital[2] * (1 + (index // 9) * .03)
        y = orbital[1] + (index % 5) * .003 * orbital[0]
        angle = index * .61
        return ((math.cos(angle) * x - math.sin(angle) * z) * AU, y * AU,
                (math.sin(angle) * x + math.cos(angle) * z) * AU)

    def site(id_, sector, name, kind, orbital, pivot):
        position = orbital_point(sector, orbital)
        insert('site_defs', dict(site_id=id_, sector_id=sector, display_name=name, site_kind=kind,
               x_m=position[0], y_m=position[1], z_m=position[2],
               pivot_x_m=float(pivot[0]), pivot_y_m=float(pivot[1]), pivot_z_m=float(pivot[2]), local_radius_m=150000.0))

    def npc_spawn(id_, sector, site_id, xyz, npc_id, behavior, mode='mission_scoped', unlock='unlock_open_routes'):
        home = id_.replace('spawn_', 'anchor_')
        anchor(home, sector, 'npc_spawn', xyz, site_id)
        patrol = home + '_patrol'
        anchor(patrol, sector, 'patrol', (xyz[0] + 60, xyz[1], xyz[2] + 80), site_id)
        insert('npc_spawn_defs', dict(spawn_id=id_, npc_id=npc_id, sector_id=sector, anchor_id=home,
               behavior_id=behavior, occurrence_mode=mode, required_unlock_id=unlock,
               respawn_s=900.0 if mode == 'ambient' else None, bounty_enabled=int(mode == 'ambient'), loot_enabled=int(mode == 'ambient')))
        insert('npc_patrol_points', dict(spawn_id=id_, point_index=0, anchor_id=patrol))
        return home

